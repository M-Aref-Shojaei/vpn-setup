def fetch_sub(source: str) -> str:
    if source.startswith("http://") or source.startswith("https://"):
        req = urllib.request.Request(source, headers={"User-Agent": "clash.meta"})
        raw = urllib.request.urlopen(req, timeout=20).read()
    else:
        raw = Path(source).read_bytes()
    # subscription may be base64-encoded link list or already YAML
    text = raw.decode("utf-8", "replace")
    if "proxies:" in text or "proxy-providers:" in text:
        return text  # clash yaml
    try:
        decoded = base64.b64decode(raw + b"===").decode("utf-8", "replace")
        if "://" in decoded:
            return decoded
    except Exception:
        pass
    return text


def b64d(s: str) -> str:
    s += "=" * (-len(s) % 4)
    return base64.urlsafe_b64decode(s).decode("utf-8", "replace")


def parse_link(link: str):
    """vmess/vless/trojan/ss/hysteria2 link -> mihomo proxy dict."""
    try:
        if link.startswith("vmess://"):
            d = json.loads(b64d(link[8:]))
            p = {
                "name": d.get("ps") or d["add"],
                "type": "vmess",
                "server": d["add"],
                "port": int(d["port"]),
                "uuid": d["id"],
                "alterId": int(d.get("aid", 0)),
                "cipher": d.get("scy") or "auto",
                "udp": True,
            }
            net = d.get("net")
            if net == "ws":
                p["network"] = "ws"
                p["ws-opts"] = {"path": d.get("path") or "/"}
                if d.get("host"):
                    p["ws-opts"]["headers"] = {"Host": d["host"]}
            elif net == "grpc":
                p["network"] = "grpc"
                p["grpc-opts"] = {"grpc-service-name": d.get("path") or ""}
            if d.get("tls") == "tls":
                p["tls"] = True
                if d.get("sni"):
                    p["servername"] = d["sni"]
                if d.get("fp"):
                    p["client-fingerprint"] = d["fp"]
            return p

        if link.startswith(("vless://", "trojan://")):
            scheme, rest = link.split("://", 1)
            u = urllib.parse.urlparse(f"{scheme}://{rest}")
            q = {k: v[0] for k, v in urllib.parse.parse_qs(u.query).items()}
            name = urllib.parse.unquote(u.fragment) or u.hostname
            p = {
                "name": name,
                "type": scheme,
                "server": u.hostname,
                "port": u.port,
                "udp": True,
            }
            if scheme == "vless":
                p["uuid"] = urllib.parse.unquote(u.username)
                if q.get("flow"):
                    p["flow"] = q["flow"]
            else:
                p["password"] = urllib.parse.unquote(u.username)
            sec = q.get("security", "")
            net = q.get("type", "tcp")
            if sec in ("tls", "reality"):
                p["tls"] = True
                if q.get("sni"):
                    p["servername"] = q["sni"]
                if q.get("fp"):
                    p["client-fingerprint"] = q["fp"]
                if sec == "reality":
                    p["reality-opts"] = {"public-key": q.get("pbk", "")}
                    if q.get("sid"):
                        p["reality-opts"]["short-id"] = q["sid"]
            if net == "ws":
                p["network"] = "ws"
                p["ws-opts"] = {"path": q.get("path", "/")}
                if q.get("host"):
                    p["ws-opts"]["headers"] = {"Host": q["host"]}
            elif net == "grpc":
                p["network"] = "grpc"
                p["grpc-opts"] = {"grpc-service-name": q.get("serviceName", "")}
            return p

        if link.startswith("ss://"):
            body = link[5:]
            frag = ""
            if "#" in body:
                body, frag = body.split("#", 1)
            name = urllib.parse.unquote(frag)
            if "@" in body:
                creds, hostport = body.rsplit("@", 1)
                if ":" not in creds:
                    creds = b64d(creds)
            else:
                decoded = b64d(body)
                creds, hostport = decoded.rsplit("@", 1)
            method, password = creds.split(":", 1)
            host, port = hostport.rsplit(":", 1)
            return {
                "name": name or host,
                "type": "ss",
                "server": host,
                "port": int(port),
                "cipher": method,
                "password": password,
                "udp": True,
            }

        if link.startswith(("hysteria2://", "hy2://")):
            rest = link.split("://", 1)[1]
            u = urllib.parse.urlparse(f"hysteria2://{rest}")
            q = {k: v[0] for k, v in urllib.parse.parse_qs(u.query).items()}
            return {
                "name": urllib.parse.unquote(u.fragment) or u.hostname,
                "type": "hysteria2",
                "server": u.hostname,
                "port": u.port,
                "password": urllib.parse.unquote(u.username),
                "sni": q.get("sni", ""),
                "skip-cert-verify": q.get("insecure", "0") == "1",
            }
    except Exception as e:
        print("  ! skipped an unparseable proxy link", file=sys.stderr)
    return None


def yaml_escape(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def proxies_to_yaml(proxies: list) -> str:
    """Dump proxy dicts as YAML without pyyaml (handles nested via json for scalars)."""
    out = ["proxies:"]
    for p in proxies:
        out.append(f"  - name: {yaml_escape(p['name'])}")
        for k, v in p.items():
            if k == "name":
                continue
            out.append(f"    {k}: {json.dumps(v, ensure_ascii=False)}")
    return "\n".join(out) + "\n"


def extract_proxies_from_clash_yaml(text: str) -> str:
    """If the sub is already Clash YAML, reuse it but strip its rules/dns/tun."""
    # crude but effective: keep everything, cut top-level blocks we override
    # split on top-level keys; list items ("- ...") belong to the previous block
    blocks = re.split(r"(?m)^(?=\S)(?!- )", text)
    keep = [
        b for b in blocks
        if not re.match(r"^(rules|rule-providers|dns|tun|proxy-groups|mode|mixed-port|port|"
                        r"socks-port|allow-lan|bind-address|log-level|external-controller|"
                        r"sniffer|ipv6|find-process-mode|global-client-fingerprint)\s*:", b)
    ]
    return "".join(keep)


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    source = sys.argv[1]
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT_PATH

    print(">> fetching subscription")
    text = fetch_sub(source)

    if "proxies:" in text:
        print(">> subscription is Clash YAML — reusing proxies/groups")
        body = extract_proxies_from_clash_yaml(text)
        has_group = "proxy-groups:" in body
        if not has_group:
            names = re.findall(r"^\s*-?\s*name:\s*['\"]?(.+?)['\"]?\s*$",
                               body, re.M)
            body += (
                "\nproxy-groups:\n"
                "  - name: PROXY\n"
                "    type: select\n"
                "    proxies:\n"
                + "".join(f"      - {yaml_escape(n)}\n" for n in names)
            )
    else:
        links = [l.strip() for l in text.splitlines() if "://" in l]
        print(f">> parsing {len(links)} subscription links")
        proxies = [p for l in links if (p := parse_link(l))]
        if not proxies:
            sys.exit("error: no usable proxies found in subscription")
        print(f">> parsed {len(proxies)} proxies")
        body = proxies_to_yaml(proxies)
        body += (
            "\nproxy-groups:\n"
            "  - name: PROXY\n"
            "    type: url-test\n"
            "    url: https://www.gstatic.com/generate_204\n"
            "    interval: 300\n"
            "    tolerance: 50\n"
            "    proxies:\n"
            + "".join(f"      - {yaml_escape(p['name'])}\n" for p in proxies)
        )

    config = HEADER + "\n" + body + RULES
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(config)
    print(f">> wrote {out}")

    # validate with mihomo itself
    mihomo = BASE_DIR / "bin" / "mihomo"
    if mihomo.exists():
        r = subprocess.run(
            [str(mihomo), "-t", "-d", str(DATA_DIR), "-f", str(out)],
            capture_output=True, text=True,
        )
        tail = (r.stdout + r.stderr).strip().splitlines()[-3:]
        print(">> mihomo config test:", *tail, sep="\n   ")
        sys.exit(r.returncode)


if __name__ == "__main__":
    main()
